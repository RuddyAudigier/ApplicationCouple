-- ---------------------------------------------------------------------
-- 6) BUDGET — enveloppe mensuelle (total) sur budget_params
--    (les dépenses détaillées vont dans la nouvelle table budget_depenses,
--     "spent" = somme des budget_depenses)
-- ---------------------------------------------------------------------
alter table public.budget_params
  add column if not exists enveloppe numeric not null default 0;

-- crée une ligne unique de paramètres si la table est vide
insert into public.budget_params (revenu_p1, revenu_p2, charges_fixes, enveloppe)
select 0, 0, '[]'::jsonb, 0
where not exists (select 1 from public.budget_params);


create table if not exists public.budget_depenses (
  id bigint generated by default as identity primary key,
  label text not null,
  amount numeric not null check (amount >= 0),
  by text not null check (by in ('p1', 'p2')),
  created_at timestamptz not null default now()
);

alter table public.budget_depenses enable row level security;

