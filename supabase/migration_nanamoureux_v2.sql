-- ---------------------------------------------------------------------
-- 9) PROFILS + APP_MEMBERS — auto-détection p1/p2
--    Crée automatiquement une ligne profiles + app_members pour chaque
--    nouvel utilisateur, et comble les lignes manquantes pour les
--    comptes déjà existants (1er compte créé = p1, 2e = p2).
-- ---------------------------------------------------------------------
-- l'email sert à retrouver l'adresse du/de la partenaire (messages, widget)
alter table public.profiles
  add column if not exists email text;

-- le nouveau design permet de renommer son profil librement (ex: "Bo"),
-- on retire donc la contrainte de longueur minimale sur "username".
alter table public.profiles
  drop constraint if exists profiles_username_check;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email) values (new.id, new.email)
  on conflict (id) do update set email = excluded.email;

  insert into public.app_members (user_id) values (new.id)
  on conflict (user_id) do nothing;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- backfill pour les comptes déjà créés
insert into public.profiles (id, email)
select id, email from auth.users
on conflict (id) do update set email = excluded.email;

insert into public.app_members (user_id)
select id from auth.users
on conflict (user_id) do nothing;

alter table public.app_members enable row level security;

drop policy if exists "app_members_select_authenticated" on public.app_members;
create policy "app_members_select_authenticated"
on public.app_members for select
to authenticated
using (true);

alter table public.profiles enable row level security;

drop policy if exists "profiles_select_authenticated" on public.profiles;
